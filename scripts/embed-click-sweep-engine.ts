/**
 * scripts/agentstoz-click-sweep.mjs(전수 클릭 엔진 원본)를 러너 scripts/agentstoz-maintainer.py에 그대로 넣는다.
 * 공통 테스터 계층이 퍼지는 길은 러너 하나뿐이라, 엔진은 러너 안에 실려 각 프로젝트에 깔린다.
 * 엔진을 고쳤으면: bun scripts/embed-click-sweep-engine.ts → 러너 VERSION 올리기 → 이전 해시를 RELEASED_RUNNERS에.
 * `--check`는 쓰지 않고 어긋났는지만 본다(tests/click-sweep-engine.test.ts가 같은 판정을 한다).
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const runnerPath = join(root, 'scripts/agentstoz-maintainer.py');
const engine = readFileSync(join(root, 'scripts/agentstoz-click-sweep.mjs'), 'utf8');
if (engine.includes("'''")) throw new Error("engine must not contain ''' (it is embedded in a Python raw string)");
const begin = '# BEGIN CLICK SWEEP ENGINE — generated by scripts/embed-click-sweep-engine.ts from scripts/agentstoz-click-sweep.mjs; do not edit here.\n';
const end = "'''\n# END CLICK SWEEP ENGINE\n";
const runner = readFileSync(runnerPath, 'utf8');
const from = runner.indexOf(begin), to = runner.indexOf(end);
if (from < 0 || to < from) throw new Error('engine markers missing in the runner');
const next = runner.slice(0, from) + begin + "CLICK_SWEEP_ENGINE = r'''" + engine + runner.slice(to);
if (process.argv.includes('--check')) {
  if (next !== runner) { console.error('embedded click-sweep engine is stale: run bun scripts/embed-click-sweep-engine.ts'); process.exit(1); }
} else if (next !== runner) { writeFileSync(runnerPath, next); console.log('embedded the click-sweep engine into the runner — bump the runner VERSION if it shipped'); }
else console.log('runner already carries this engine');
