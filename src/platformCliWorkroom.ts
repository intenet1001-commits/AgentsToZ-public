import {execFile,spawn} from 'node:child_process';
import {chmodSync,existsSync,mkdirSync,realpathSync,renameSync,writeFileSync} from 'node:fs';
import {basename,delimiter,dirname,isAbsolute,join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {PLATFORM_CLI_DEFAULT_ACCOUNT,PLATFORM_CLI_PROVIDERS,type PlatformCliProvider,type PlatformCliBinding} from './platformCliProtocol';

/**
 * A project's own CLI account inside its Workrooms — the 「로컬」 half of the account switch.
 *
 * Precedence: the project's account > this Mac's login (the Mac-wide switch) > nothing else. Never a token in the
 * Workroom environment: `gh`·`supabase`·`vercel`·`gws` resolve through small shims that ask, at each call, which
 * account the project uses now — so a switch in the project screen applies to the next command, without a restart.
 * A project that follows this Mac runs the real CLI untouched. `git push` to github.com asks the same question
 * through a credential helper placed ahead of this Mac's own helpers, which it falls back to unchanged.
 */
export const PLATFORM_CLI_BINARIES:Record<PlatformCliProvider,string>={github:'gh',supabase:'supabase',vercel:'vercel','google-workspace':'gws'};
export const PLATFORM_CLI_SHIM_DIR_ENV='AGENTSTOZ_CLI_SHIM_DIR';
export const PLATFORM_GIT_FALLBACK_ENV='AGENTSTOZ_GIT_CREDENTIAL_FALLBACK';
const GITHUB_HELPER_KEY='credential.https://github.com.helper';
const quote=(value:string)=>`'${value.replaceAll("'",`'\\''`)}'`;

/** The account a project's binding names, or null when the project follows this Mac. */
export function platformCliProjectAccountId(binding:PlatformCliBinding|null|undefined):string|null {
  return binding&&binding.accountId!==PLATFORM_CLI_DEFAULT_ACCOUNT?binding.accountId:null;
}

export function platformCliShimScript(provider:PlatformCliProvider,launcher:string,real:string):string {
  return `#!/bin/sh
# Generated by AgentsToZ — do not edit. Runs ${PLATFORM_CLI_BINARIES[provider]} with this project's own CLI account
# when the project has one, otherwise exactly as this Mac would. No token is kept here or in the environment.
if [ -x ${quote(launcher)} ]; then exec ${quote(launcher)} cli-exec ${provider} --real ${quote(real)} -- "$@"; fi
exec ${quote(real)} "$@"
`;
}

/** Writes one shim per installed CLI; returns its directory, or null when there is nothing to route through. */
export function preparePlatformCliShims(directory:string,launcher:string,executable:(provider:PlatformCliProvider)=>string|null|undefined):string|null {
  if(process.platform==='win32'||!existsSync(launcher))return null;
  mkdirSync(directory,{recursive:true,mode:0o700});
  let written=0;
  for(const provider of PLATFORM_CLI_PROVIDERS){
    const real=executable(provider);
    if(!real||!isAbsolute(real)||dirname(real)===directory)continue;
    // Concurrent Workroom starts each write a whole file and rename it into place.
    const target=join(directory,PLATFORM_CLI_BINARIES[provider]),temporary=`${target}.${randomUUID()}.tmp`;
    writeFileSync(temporary,platformCliShimScript(provider,launcher,real),{mode:0o755});chmodSync(temporary,0o755);renameSync(temporary,target);written++;
  }
  return written?directory:null;
}

/** The credential helpers git asks for github.com, in order; an empty helper resets the list (git's own rule). */
export function githubCredentialChain(configNull:string):string[] {
  const chain:string[]=[];
  for(const entry of configNull.split('\0')){
    if(!entry)continue;const split=entry.indexOf('\n'),key=split<0?entry:entry.slice(0,split),value=split<0?'':entry.slice(split+1);
    const match=/^credential\.(?:(.+)\.)?helper$/i.exec(key);if(!match)continue;
    if(match[1]!==undefined&&!/^https:\/\/github\.com\/?$/i.test(match[1]))continue;
    if(value==='')chain.length=0;else chain.push(value);
  }
  return chain;
}
/** Where AgentsToZ keeps its own github.com routing for git outside Workrooms (platformCliEverywhere.ts). */
export function platformCliGitFiles(root:string){const dir=join(root,'git');return {dir,include:join(dir,'github.gitconfig'),helper:join(dir,'credential-helper')};}
/** git config --null --show-origin: `origin\0key\nvalue\0` per entry. */
export function parseCredentialOrigins(stdout:string):{origin:string;key:string;value:string}[] {
  const parts=stdout.split('\0'),entries:{origin:string;key:string;value:string}[]=[];
  for(let i=0;i+1<parts.length;i+=2){
    const origin=parts[i]!,entry=parts[i+1]!;if(!entry)continue;
    const split=entry.indexOf('\n');entries.push({origin,key:split<0?entry:entry.slice(0,split),value:split<0?'':entry.slice(split+1)});
  }
  return entries;
}
/** The github.com helpers this Mac's own git config gives, leaving out AgentsToZ's routing (never a helper that calls back here). */
export function macGithubCredentialChain(stdout:string,own:{include:string;helper:string;launcher?:string}):string[] {
  const chain:string[]=[];
  for(const {origin,key,value} of parseCredentialOrigins(stdout)){
    if(origin==='file:'+own.include)continue;
    const match=/^credential\.(?:(.+)\.)?helper$/i.exec(key);if(!match)continue;
    if(match[1]!==undefined&&!/^https:\/\/github\.com\/?$/i.test(match[1]))continue;
    if(value==='')chain.length=0;else chain.push(value);
  }
  return chain.filter(spec=>!spec.includes(own.helper)&&!(own.launcher&&spec.includes(own.launcher)&&/\bgit-credential\b/.test(spec)));
}
export function readGitConfig(git:string,args:string[],cwd:string,env:NodeJS.ProcessEnv):Promise<{code:number;stdout:string}> {
  return new Promise(resolve=>execFile(git,args,{cwd,env,timeout:5000,encoding:'utf8',maxBuffer:256*1024},(error,stdout)=>{
    const code=error?typeof (error as {code?:unknown}).code==='number'?(error as {code:number}).code:-1:0;resolve({code,stdout:stdout??''});
  }));
}
export async function readMacGithubCredentialChain(git:string,cwd:string,env:NodeJS.ProcessEnv,own:{include:string;helper:string;launcher?:string}):Promise<string[]|null> {
  const r=await readGitConfig(git,['config','--null','--show-origin','--get-regexp','^credential\\.'],cwd,env);
  // Exit 1 is 「no such key」: no helper at all.
  return r.code===0||r.code===1?macGithubCredentialChain(r.stdout,own):null;
}

/** Environment additions for one Workroom. Empty when nothing can be routed (no launcher, Windows). */
export async function platformCliWorkroomEnvironment(input:{shimDirectory:string;launcher:string;cwd:string;env:Record<string,string|undefined>;git:string|null;
  executable:(provider:PlatformCliProvider)=>string|null|undefined}):Promise<Record<string,string>> {
  const shims=preparePlatformCliShims(input.shimDirectory,input.launcher,input.executable);if(!shims)return {};
  const path=(input.env.PATH??'').split(delimiter).filter(entry=>entry&&entry!==shims);
  const patch:Record<string,string>={PATH:[shims,...path].join(delimiter),[PLATFORM_CLI_SHIM_DIR_ENV]:shims};
  const count=input.env.GIT_CONFIG_COUNT===undefined||input.env.GIT_CONFIG_COUNT===''?0:Number(input.env.GIT_CONFIG_COUNT);
  if(input.git&&isAbsolute(input.git)&&Number.isSafeInteger(count)&&count>=0&&count<64){
    // This Mac's own helpers, never AgentsToZ's own routing for the rest of the Mac (it would only call back here).
    const fallback=await readMacGithubCredentialChain(input.git,input.cwd,input.env as NodeJS.ProcessEnv,{...platformCliGitFiles(dirname(input.shimDirectory)),launcher:input.launcher})??[];
    Object.assign(patch,{GIT_CONFIG_COUNT:String(count+2),
      [`GIT_CONFIG_KEY_${count}`]:GITHUB_HELPER_KEY,[`GIT_CONFIG_VALUE_${count}`]:'',
      [`GIT_CONFIG_KEY_${count+1}`]:GITHUB_HELPER_KEY,[`GIT_CONFIG_VALUE_${count+1}`]:`!${quote(input.launcher)} git-credential`,
      [PLATFORM_GIT_FALLBACK_ENV]:JSON.stringify(fallback)});
  }
  return patch;
}

/** The real CLI on PATH, never one of the shims. */
export function platformCliRealExecutable(provider:PlatformCliProvider,env:NodeJS.ProcessEnv=process.env,shimDirectory?:string):string|null {
  const skip=new Set([env[PLATFORM_CLI_SHIM_DIR_ENV],shimDirectory].filter((v):v is string=>!!v));
  for(const entry of (env.PATH??'').split(delimiter)){
    if(!entry||!isAbsolute(entry)||skip.has(entry))continue;
    const candidate=join(entry,PLATFORM_CLI_BINARIES[provider]);
    try{if(existsSync(candidate)&&!skip.has(dirname(realpathSync(candidate))))return candidate;}catch{}
  }
  return null;
}
/** A real CLI path a shim names: absolute, the provider's own binary, not inside the shim directory. */
export function platformCliShimTarget(provider:PlatformCliProvider,real:string,env:NodeJS.ProcessEnv=process.env):string|null {
  if(!isAbsolute(real)||basename(real)!==PLATFORM_CLI_BINARIES[provider]||!existsSync(real))return null;
  const shims=env[PLATFORM_CLI_SHIM_DIR_ENV];if(shims&&dirname(real)===shims)return null;
  return real;
}

/** gh commands that would print the project's token. The account is used, never shown. */
export function platformCliRevealsToken(provider:PlatformCliProvider,args:readonly string[]):boolean {
  if(provider!=='github'||args[0]!=='auth')return false;
  return args[1]==='token'||args[1]==='git-credential'||args[1]==='status'&&args.some(a=>a==='-t'||a==='--show-token'||/^-[a-zA-Z]*t/.test(a)&&!a.startsWith('--'));
}

/** Runs a CLI attached to this terminal and returns its exit status. */
export function runAttached(executable:string,args:string[],env:NodeJS.ProcessEnv,cwd:string):Promise<number> {
  return new Promise(resolve=>{
    const child=spawn(executable,args,{cwd,env,stdio:'inherit'});
    const forward=(signal:NodeJS.Signals)=>()=>{try{child.kill(signal);}catch{}};
    // The terminal's Ctrl-C reaches the CLI directly; this process only waits for it.
    const onInt=()=>{},onTerm=forward('SIGTERM'),onHup=forward('SIGHUP');
    process.on('SIGINT',onInt);process.on('SIGTERM',onTerm);process.on('SIGHUP',onHup);
    const done=(code:number)=>{process.off('SIGINT',onInt);process.off('SIGTERM',onTerm);process.off('SIGHUP',onHup);resolve(code);};
    child.on('error',()=>done(127));
    child.on('exit',(code,signal)=>done(code??(signal?128+(({SIGINT:2,SIGTERM:15,SIGHUP:1,SIGKILL:9} as Record<string,number>)[signal]??1):1)));
  });
}

/** git credential protocol: `key=value` lines. */
export function parseGitCredential(text:string):Record<string,string> {
  const fields:Record<string,string>={};
  for(const line of text.split('\n')){const at=line.indexOf('=');if(at>0&&!line.endsWith('[]'))fields[line.slice(0,at)]=line.slice(at+1).replace(/\r$/,'');}
  return fields;
}
export function gitFallbackHelpers(value:string|undefined):string[] {
  try{const list=JSON.parse(value??'[]');return Array.isArray(list)?list.filter(v=>typeof v==='string'&&v.length>0&&v.length<=2048).slice(0,16):[];}catch{return [];}
}
/** How git itself runs a helper spec: `!cmd` through the shell, an absolute path as is, otherwise `git credential-<name>`. */
export function gitHelperCommand(spec:string):string {
  if(spec.startsWith('!'))return spec.slice(1);
  return isAbsolute(spec.split(/\s/)[0]!)?spec:`git credential-${spec}`;
}
export function runGitHelper(spec:string,action:string,input:string,env:NodeJS.ProcessEnv):Promise<string> {
  return new Promise(resolve=>{
    const child=spawn('/bin/sh',['-c',`${gitHelperCommand(spec)} "$@"`,'git-credential-helper',action],{env,stdio:['pipe','pipe','ignore']});
    const output:Buffer[]=[];let size=0;
    child.stdout!.on('data',(chunk:Buffer)=>{size+=chunk.length;if(size<=64*1024)output.push(chunk);});
    child.stdin!.on('error',()=>{});child.stdin!.end(input);
    const timer=setTimeout(()=>{try{child.kill('SIGKILL');}catch{}},120_000);
    child.on('error',()=>{clearTimeout(timer);resolve('');});
    child.on('close',()=>{clearTimeout(timer);resolve(Buffer.concat(output).toString('utf8'));});
  });
}
/** The helpers' own environment: without the Workroom's routing, so a helper that runs git cannot loop back here. */
export function gitHelperEnvironment(env:NodeJS.ProcessEnv):NodeJS.ProcessEnv {
  const next={...env};
  for(const key of Object.keys(next))if(/^GIT_CONFIG_(?:COUNT|KEY_\d+|VALUE_\d+)$/.test(key)||key===PLATFORM_GIT_FALLBACK_ENV)delete next[key];
  const shims=next[PLATFORM_CLI_SHIM_DIR_ENV];
  if(shims)next.PATH=(next.PATH??'').split(delimiter).filter(entry=>entry!==shims).join(delimiter);
  delete next[PLATFORM_CLI_SHIM_DIR_ENV];
  return next;
}
