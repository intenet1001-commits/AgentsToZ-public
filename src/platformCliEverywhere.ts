/**
 * A project's own CLI account wherever that folder is used — not only in Workrooms.
 *
 * - Terminals (Terminal, iTerm, an IDE's terminal, the shells AI apps open): a managed block at the end of the
 *   shell startup files puts the same shims first on PATH. A shim asks at each call which account the folder's
 *   project uses; outside a registered project, or for a project following this Mac, the real CLI runs untouched.
 * - git (any terminal or app that runs git, such as an IDE's source control): one managed include at the end of
 *   the global git config asks AgentsToZ first for github.com. Everything else goes to this Mac's own helpers,
 *   in the order git used before; when AgentsToZ is gone the helper script runs those helpers itself.
 *
 * Only AgentsToZ's own block and include are ever added, moved or removed. Off removes both.
 */
export const PLATFORM_CLI_SHELL_BEGIN='# >>> AgentsToZ CLI accounts >>>';
export const PLATFORM_CLI_SHELL_END='# <<< AgentsToZ CLI accounts <<<';
const DOTFILE_LIMIT=1024*1024;
const quote=(value:string)=>`'${value.replaceAll("'",`'\\''`)}'`;


export function platformCliShellBlock(shims:string):string {
  return [PLATFORM_CLI_SHELL_BEGIN,
    '# 아젠투지에 등록된 프로젝트 폴더에서는 그 프로젝트가 고른 gh·supabase·vercel·gws 계정을 씁니다. 그 밖에서는 그대로입니다.',
    '# 아젠투지 설정 → CLI 계정 전환에서 끄면 이 부분이 지워집니다.',
    `_atz_cli_shims=${quote(shims)}`,
    'if [ -d "$_atz_cli_shims" ]; then',
    '  PATH=":$PATH:"; PATH="${PATH//":$_atz_cli_shims:"/:}"; PATH="${PATH#:}"; PATH="${PATH%:}"',
    '  export PATH="$_atz_cli_shims${PATH:+:$PATH}" '+PLATFORM_CLI_SHIM_DIR_ENV+'="$_atz_cli_shims"',
    'fi',
    'unset _atz_cli_shims',
    PLATFORM_CLI_SHELL_END].join('\n');
}

/** The file's text with AgentsToZ's block removed and, when given, appended last. Null when the file holds a broken block. */
export function withShellBlock(text:string,block:string|null):string|null {
  const lines=text.split('\n'),kept:string[]=[];let inside=false;
  for(const line of lines){
    if(line.trim()===PLATFORM_CLI_SHELL_BEGIN){if(inside)return null;inside=true;if(kept.length&&kept[kept.length-1]==='')kept.pop();continue;}
    if(line.trim()===PLATFORM_CLI_SHELL_END){if(!inside)return null;inside=false;continue;}
    if(!inside)kept.push(line);
  }
  if(inside)return null;
  const base=kept.join('\n').replace(/\n+$/,'');
  if(!block)return base?base+'\n':'';
  return (base?base+'\n\n':'')+block+'\n';
}
export function hasShellBlock(text:string):boolean {return text.split('\n').some(l=>l.trim()===PLATFORM_CLI_SHELL_BEGIN);}

/** The helper git runs; without AgentsToZ it runs this Mac's own helpers itself, in git's order. */
export function platformCliGitHelperScript(launcher:string,fallback:string[]):string {
  const lines=['#!/bin/sh','# Generated by AgentsToZ — do not edit. Answers github.com for a project that chose its own GitHub account,',
    '# and leaves every other request to the helpers this Mac used before.',
    `if [ -x ${quote(launcher)} ]; then exec ${quote(launcher)} git-credential "$@"; fi`,
    'input=$(cat)'];
  for(const spec of fallback)lines.push(`out=$(printf '%s\\n\\n' "$input" | ${gitHelperCommand(spec)} "$@" 2>/dev/null)`,
    'case "$out" in *password=*|*quit=*) if [ "$1" = get ]; then printf \'%s\\n\' "$out"; exit 0; fi;; esac');
  lines.push('exit 0','');
  return lines.join('\n');
}
export function platformCliGitInclude(helper:string):string {
  const value=`!${quote(helper)}`.replaceAll('\\','\\\\').replaceAll('"','\\"');
  return `# Generated by AgentsToZ — do not edit. Off in AgentsToZ settings removes it.\n[credential "https://github.com"]\n\thelper =\n\thelper = "${value}"\n`;
}

export type PlatformCliEverywhereMode='auto'|'on'|'off';
export interface PlatformCliEverywhereStatus {
  mode:PlatformCliEverywhereMode;
  /** on: terminals and git both route; partial: one of them; off: Workrooms only; pending: on, waiting for a project account. */
  state:'on'|'partial'|'off'|'pending'|'unsupported';
  shell:string[];git:boolean;message?:string;
}
export interface PlatformCliEverywhereDependencies {
  store:PlatformCliStore;launcher:string;git:string|null;
  executable:(provider:PlatformCliProvider)=>string|null|undefined;
  home?:string;env?:NodeJS.ProcessEnv;shell?:string;
  /** The installed app applies the default by itself; a dev or test server changes nothing until asked. */
  autoApply:boolean;
}

function readDotfile(path:string):string|null {
  try{const s=statSync(path);if(!s.isFile()||s.size>DOTFILE_LIMIT)return null;return readFileSync(path,'utf8');}catch{return null;}
}
/** Replaces a startup file whole, through a symlink to its real file, keeping its mode. */
function writeDotfile(path:string,text:string){
  let target=path;try{if(lstatSync(path).isSymbolicLink())target=realpathSync(path);}catch{}
  let mode=0o644;try{mode=statSync(target).mode&0o777;}catch{}
  const temporary=join(dirname(target),`.${basename(target)}.agentstoz-${randomUUID()}`);
  writeFileSync(temporary,text,{mode});chmodSync(temporary,mode);renameSync(temporary,target);
}

export class PlatformCliEverywhere {
  constructor(private readonly deps:PlatformCliEverywhereDependencies){}
  private get root(){return this.deps.store.root;}
  private get env():NodeJS.ProcessEnv{return this.deps.env??process.env;}
  private get home(){return this.deps.home??this.env.HOME??homedir();}
  private get shims(){return join(this.root,'shims');}
  private get files(){return platformCliGitFiles(this.root);}
  private modeFile(){return join(this.root,'everywhere.json');}
  mode():PlatformCliEverywhereMode {
    try{const raw=readPrivateFileStrict(this.modeFile());if(!raw)return 'auto';const m=JSON.parse(raw).mode;return m==='on'||m==='off'?m:'auto';}catch{return 'auto';}
  }
  /** zsh's and bash's startup files: the ones present, plus zsh's own when zsh is the login shell. */
  private shellFiles():string[] {
    const zdot=this.env.ZDOTDIR&&isAbsolute(this.env.ZDOTDIR)?this.env.ZDOTDIR:this.home;
    let shell=this.deps.shell??'';if(!shell)try{shell=userInfo().shell??'';}catch{}
    const zsh=!shell||/\/zsh$/.test(shell),bash=/\/bash$/.test(shell);
    const candidates:[string,boolean][]=[[join(zdot,'.zprofile'),zsh],[join(zdot,'.zshrc'),zsh],[join(this.home,'.bash_profile'),bash],[join(this.home,'.bashrc'),false]];
    return candidates.filter(([file,create])=>create||existsSync(file)).map(([file])=>file);
  }
  private display(file:string){return file.startsWith(this.home+'/')?'~/'+file.slice(this.home.length+1):file;}
  private async gitState():Promise<{applied:boolean;last:boolean}|null> {
    const git=this.deps.git;if(!git||!isAbsolute(git))return null;
    const r=await readGitConfig(git,['config','--global','--null','--get-regexp','^(include\\.path|includeif\\..+\\.path|credential\\..+)$'],this.home,this.env);
    if(r.code!==0&&r.code!==1)return null;
    const entries=r.stdout.split('\0').filter(Boolean).map(e=>{const i=e.indexOf('\n');return {key:i<0?e:e.slice(0,i),value:i<0?'':e.slice(i+1)};});
    const ours=entries.filter(e=>e.key==='include.path'&&e.value===this.files.include);
    const last=entries.at(-1);
    return {applied:ours.length>0&&existsSync(this.files.include),last:ours.length===1&&!!last&&last.key==='include.path'&&last.value===this.files.include};
  }
  async status():Promise<PlatformCliEverywhereStatus> {
    const mode=this.mode();
    if(process.platform==='win32')return {mode,state:'unsupported',shell:[],git:false,message:'Windows에서는 아젠투지 워크룸에서만 프로젝트 계정을 씁니다.'};
    const shell=this.shellFiles().filter(f=>{const t=readDotfile(f);return t!==null&&hasShellBlock(t);}).map(f=>this.display(f));
    const git=(await this.gitState())?.last??false;
    let state:PlatformCliEverywhereStatus['state'];
    if(shell.length>0||git)state=shell.length>0&&git?'on':'partial';
    else if(mode==='off')state='off';
    // Chosen, or a project already has its own account, but nothing is in place yet.
    else if(mode==='on'||this.deps.store.hasProjectAccounts())state=existsSync(this.deps.launcher)?'partial':'unsupported';
    else state='pending';
    const message=state==='unsupported'?'아젠투지 앱을 한 번 실행하면 준비됩니다.':state!=='partial'?undefined
      :!git?'git은 아직 이 Mac의 인증 도우미만 씁니다. 다시 적용하세요.':'터미널 설정 파일에 아직 적용되지 않았습니다. 다시 적용하세요.';
    return {mode,state,shell,git,...(message?{message}:{})};
  }
  async set(enabled:boolean):Promise<PlatformCliEverywhereStatus> {
    this.deps.store.ensureDirectory();
    writePrivateFileAtomically(this.root,this.modeFile(),JSON.stringify({schemaVersion:1,mode:enabled?'on':'off'}));
    return this.apply(enabled);
  }
  /** Brings files in line with the chosen mode. `auto` applies once a project has its own account and never removes. */
  async reconcile(trigger:'start'|'bind'|'git-setup'):Promise<PlatformCliEverywhereStatus> {
    const mode=this.mode();
    if(mode==='off')return trigger==='start'?this.status():this.apply(false);
    if(mode==='auto'&&(!this.deps.autoApply||!this.deps.store.hasProjectAccounts()))return this.status();
    return this.apply(true);
  }
  private apply(enabled:boolean):Promise<PlatformCliEverywhereStatus> {
    if(process.platform==='win32')return this.status();
    this.deps.store.ensureDirectory();
    return withOwnedPortalFileLock(join(this.root,'everywhere.lock'),async()=>{
      const problems:string[]=[];
      const shims=enabled?preparePlatformCliShims(this.shims,this.deps.launcher,this.deps.executable):null;
      if(enabled&&!shims)problems.push('터미널: 아젠투지 실행기나 CLI가 아직 없습니다');
      for(const file of this.shellFiles()){
        const current=existsSync(file)?readDotfile(file):'';
        if(current===null){problems.push(this.display(file)+'을(를) 읽지 못했습니다');continue;}
        if(!shims&&!hasShellBlock(current))continue;
        const next=withShellBlock(current,shims?platformCliShellBlock(shims):null);
        if(next===null){problems.push(this.display(file)+'의 아젠투지 부분이 손상되어 그대로 두었습니다');continue;}
        if(next!==current)try{writeDotfile(file,next);}catch{problems.push(this.display(file)+'에 쓰지 못했습니다');}
      }
      try{await this.applyGit(enabled);}catch(error){problems.push(error instanceof PlatformCliError?error.message:'git 설정을 바꾸지 못했습니다');}
      const status=await this.status();
      return problems.length?{...status,message:problems.join(' · ')}:status;
    },{label:'Platform CLI everywhere',attempts:50,retryMs:40,deadOwnerRecoveryClass:'manual',canRecoverDeadOwner:()=>false});
  }
  private async applyGit(enabled:boolean){
    const git=this.deps.git;if(!git||!isAbsolute(git))return;
    const files=this.files,env=this.env,cwd=this.home;
    const remove=async()=>{const r=await readGitConfig(git,['config','--global','--fixed-value','--unset-all','include.path',files.include],cwd,env);if(r.code!==0&&r.code!==5)throw new PlatformCliError('git 전역 설정에서 아젠투지 항목을 지우지 못했습니다');};
    if(!enabled){
      const present=await readGitConfig(git,['config','--global','--fixed-value','--get-all','include.path',files.include],cwd,env);
      if(present.code===0)await remove();
      rmSync(files.include,{force:true});rmSync(files.helper,{force:true});return;
    }
    const state=await this.gitState();if(!state)throw new PlatformCliError('git 전역 설정을 읽지 못했습니다');
    if(!existsSync(this.deps.launcher))return;
    const fallback=await readMacGithubCredentialChain(git,cwd,env,{...files,launcher:this.deps.launcher});
    if(fallback===null)throw new PlatformCliError('git 인증 도우미 목록을 읽지 못했습니다');
    mkdirSync(files.dir,{recursive:true,mode:0o700});
    const script=platformCliGitHelperScript(this.deps.launcher,fallback);
    if(readDotfile(files.helper)!==script)writePrivateFileAtomically(files.dir,files.helper,script);
    chmodSync(files.helper,0o700);
    const include=platformCliGitInclude(files.helper);
    if(readDotfile(files.include)!==include)writePrivateFileAtomically(files.dir,files.include,include);
    // Last in the global config, so nothing after it puts another github.com helper first.
    if(!state.last){
      await remove();
      const r=await readGitConfig(git,['config','--global','--add','include.path',files.include],cwd,env);
      if(r.code!==0)throw new PlatformCliError('git 전역 설정에 아젠투지 항목을 넣지 못했습니다');
    }
  }
}

const registered=new WeakMap<object,PlatformCliEverywhere>();
export function registerPlatformCliEverywhere(owner:object,everywhere:PlatformCliEverywhere){registered.set(owner,everywhere);return everywhere;}
export function platformCliEverywhere(owner:object):PlatformCliEverywhere|null {return registered.get(owner)??null;}
